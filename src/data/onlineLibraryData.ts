export function searchLibrary(query: string, filters?: {
  discipline?: string;
  type?: LibraryResource['type'];
  isFree?: boolean;
  level?: string;
}): LibraryResource[] {
  let results = [...ALL_LIBRARY_RESOURCES];

  // Text search
  if (query) {
    const q = query.toLowerCase();
    results = results.filter(r =>
      r.title.toLowerCase().includes(q) ||
      r.authors.toLowerCase().includes(q) ||
      r.subject.toLowerCase().includes(q) ||
      r.tags.some(t => t.toLowerCase().includes(q)) ||
      r.description.toLowerCase().includes(q)
    );
  }

  // Filters
  if (filters?.discipline) {
    results = results.filter(r => r.discipline === filters.discipline);
  }
  if (filters?.type) {
    results = results.filter(r => r.type === filters.type);
  }
  if (filters?.isFree !== undefined) {
    results = results.filter(r => r.isFree === filters.isFree);
  }
  if (filters?.level) {
    results = results.filter(r => r.level.includes(filters.level as any));
  }

  return results;
}
