export function searchDigitalLibrary(
  query: string,
  options?: {
    categories?: string[];
    types?: DigitalLibraryResource['type'][];
    freeOnly?: boolean;
    maxResults?: number;
  }
): DigitalLibraryResource[] {
  const lowerQuery = query.toLowerCase();
  let results = DIGITAL_LIBRARY.filter((resource) => {
    const matchesQuery =
      resource.title.toLowerCase().includes(lowerQuery) ||
      resource.authors.toLowerCase().includes(lowerQuery) ||
      resource.keywords.toLowerCase().includes(lowerQuery) ||
      resource.subjects.some((s) => s.toLowerCase().includes(lowerQuery)) ||
      (resource.description && resource.description.toLowerCase().includes(lowerQuery));

    const matchesCategory = !options?.categories || options.categories.length === 0 || options.categories.includes(resource.libraryCategory);

    const matchesType = !options?.types || options.types.length === 0 || options.types.includes(resource.type);

    const matchesFree = !options?.freeOnly || resource.isFree;

    return matchesQuery && matchesCategory && matchesType && matchesFree;
  });

  if (options?.maxResults && options.maxResults > 0) {
    results = results.slice(0, options.maxResults);
  }

  return results;
}

export function getResourcesByCategory(categoryId: string): DigitalLibraryResource[] {
  return DIGITAL_LIBRARY.filter((resource) => resource.libraryCategory === categoryId);
}

export function getResourcesByCurriculumUnit(unitId: string): DigitalLibraryResource[] {
  return DIGITAL_LIBRARY.filter((resource) => resource.curriculumUnits && resource.curriculumUnits.includes(unitId));
}

export function getResourcesByDisease(diseaseId: string): DigitalLibraryResource[] {
  return DIGITAL_LIBRARY.filter((resource) => resource.relatedDiseaseIds && resource.relatedDiseaseIds.includes(diseaseId));
}

export function getResourcesByDrug(drugId: string): DigitalLibraryResource[] {
  return DIGITAL_LIBRARY.filter((resource) => resource.relatedDrugIds && resource.relatedDrugIds.includes(drugId));
}

export function getLibraryStats(): { total: number; free: number; byCategory: Record<string, number> } {
  const total = DIGITAL_LIBRARY.length;
  const free = DIGITAL_LIBRARY.filter((r) => r.isFree).length;
  const byCategory: Record<string, number> = {};

  for (const resource of DIGITAL_LIBRARY) {
    byCategory[resource.libraryCategory] = (byCategory[resource.libraryCategory] || 0) + 1;
  }

  return { total, free, byCategory };
}
